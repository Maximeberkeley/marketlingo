"""Write the hand-written lessons (days 6-30) into the load-handwritten-lessons edge functions.

The 00NN_<market>_handwritten_days_6_30.sql migrations are about 0.7 MB each, too large for Lovable to paste,
so the same rows ship inside edge functions instead: Lovable deploys them from the repo and calls each once,
and each function upserts every stack whose content changed and replaces its slides. The rows come from the
same builder as the migrations (build.stack_rows), so the two never disagree.

Usage:
  python3 scripts/lessons/export_loader.py           # rewrite the data files
  python3 scripts/lessons/export_loader.py --check   # exit 1 if any file is out of date

Markets are split across load-handwritten-lessons, load-handwritten-lessons-2, ... in order, each bundle kept
under BUNDLE_LIMIT bytes, because one edge function deploys at most about 4.5 MB.

Markets are every drizzle/migrations/00NN_<market>_handwritten_days_6_30.sql with a scripts/lessons/<market>/ folder.
"""
import glob, hashlib, importlib.util, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
FUNCTIONS = os.path.join(ROOT, 'supabase', 'functions')
BUNDLE_LIMIT = 3_200_000
NAME = 'load-handwritten-lessons'

_spec = importlib.util.spec_from_file_location('lesson_build', os.path.join(HERE, 'build.py'))
build = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(build)


def function_dir(group):
    return os.path.join(FUNCTIONS, NAME if group == 0 else f'{NAME}-{group + 1}')


def markets():
    found = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'drizzle', 'migrations', '*_handwritten_days_6_30.sql'))):
        m = re.match(r'^\d{4}_([a-z0-9]+)_handwritten_days_6_30\.sql$', os.path.basename(path))
        if m and glob.glob(os.path.join(HERE, m.group(1), 'days_*.py')):
            found.append(m.group(1))
    return found


def fingerprint(row):
    return hashlib.sha256(json.dumps(row, ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:12]


def rows(market):
    src, lessons = build.load(sorted(glob.glob(os.path.join(HERE, market, 'days_*.py'))))
    out = []
    for r in build.stack_rows(src, lessons, market):
        r = dict(r)
        r['fingerprint'] = fingerprint(r)
        out.append(r)
    return out


def outputs():
    files = {}
    groups, size = [[]], 0
    for m in markets():
        data = json.dumps(rows(m), ensure_ascii=False, separators=(',', ':'))
        text = (f'// Generated by scripts/lessons/export_loader.py from scripts/lessons/{m}/. Do not edit by hand.\n'
                f'// Typed as unknown[] so a type check never infers this whole literal.\n'
                f'const rows: unknown[] = {data};\n\nexport default rows;\n')
        if groups[-1] and size + len(text.encode()) > BUNDLE_LIMIT:
            groups.append([]); size = 0
        groups[-1].append(m); size += len(text.encode())
        files[os.path.join(function_dir(len(groups) - 1), 'data', f'{m}.ts')] = text
    for g, names in enumerate(groups):
        fn = function_dir(g)
        imports = ''.join(f"import {m} from './{m}.ts';\n" for m in names)
        files[os.path.join(fn, 'data', 'index.ts')] = (
            '// Generated by scripts/lessons/export_loader.py. Do not edit by hand.\n' + imports +
            '\n/** The hand-written lessons bundled with this function, by market, as stacks rows with their slides. */\n'
            f"export const LESSONS = {{ {', '.join(names)} }};\n")
        files[os.path.join(fn, 'index.ts')] = (
            "// Generated by scripts/lessons/export_loader.py. Loads this function's share of the hand-written lessons;\n"
            '// see supabase/functions/_shared/handwritten-loader.ts.\n'
            'import { serveHandwrittenLoader } from "../_shared/handwritten-loader.ts";\n'
            'import { LESSONS } from "./data/index.ts";\n\nserveHandwrittenLoader(LESSONS);\n')
    return files, [os.path.basename(function_dir(g)) for g in range(len(groups))]


def config_text(current, names):
    """supabase/config.toml with a verify_jwt = false block for every loader function."""
    for name in names:
        block = f'[functions.{name}]\nverify_jwt = false\n'
        if f'[functions.{name}]' not in current:
            current = current.rstrip('\n') + '\n\n' + block
    return current


if __name__ == '__main__':
    check = '--check' in sys.argv
    stale = []
    files, names = outputs()
    config_path = os.path.join(ROOT, 'supabase', 'config.toml')
    files[config_path] = config_text(open(config_path, encoding='utf-8').read(), names)
    for path, text in files.items():
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if current == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w', encoding='utf-8').write(text)
    for path in glob.glob(os.path.join(FUNCTIONS, f'{NAME}*', 'data', '*.ts')):
        if path not in files:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.remove(path)
    if check and stale:
        print('out of date:', ', '.join(stale))
        sys.exit(1)
    print(('up to date' if check else f'wrote {len(stale)} file(s)') + f": {', '.join(markets())} -> {', '.join(names)}")
