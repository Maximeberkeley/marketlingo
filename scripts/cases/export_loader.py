"""Write the Deep Cases into the load-deep-cases edge functions, and the table schema for a Lovable migration.

Lovable runs schema changes and data separately and cannot paste a 500 KB data file through its tools. So
the cases ship inside an edge function instead: Lovable deploys it from the repo and calls it once, and the
function upserts every case whose content changed. The rows come from the same builder as the SQL
migrations (build.rows_for), so the two never disagree.

Usage:
  python3 scripts/cases/export_loader.py           # rewrite the data files
  python3 scripts/cases/export_loader.py --check   # exit 1 if any file is out of date

Markets are split across load-deep-cases, load-deep-cases-2, ... in order, each bundle kept under
BUNDLE_LIMIT bytes, because one edge function deploys at most about 4.5 MB.

Markets are every drizzle/migrations/00NN_<market>_deep_cases.sql with a scripts/cases/<market>/ folder.
"""
import glob, importlib.util, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
FUNCTIONS = os.path.join(ROOT, 'supabase', 'functions')
BUNDLE_LIMIT = 3_200_000


def function_dir(group):
    return os.path.join(FUNCTIONS, 'load-deep-cases' if group == 0 else f'load-deep-cases-{group + 1}')
SCHEMA_OUT = os.path.join(HERE, 'supabase', 'deep_cases_schema.sql')

_spec = importlib.util.spec_from_file_location('case_build', os.path.join(HERE, 'build.py'))
build = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(build)


def markets():
    found = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'drizzle', 'migrations', '*_deep_cases.sql'))):
        m = re.match(r'^\d{4}_([a-z0-9]+)_deep_cases\.sql$', os.path.basename(path))
        if m and glob.glob(os.path.join(HERE, m.group(1), 'days_*.py')):
            found.append(m.group(1))
    return found


def rows(market):
    src, cases = build.load(sorted(glob.glob(os.path.join(HERE, market, 'days_*.py'))))
    for c in cases:
        c.setdefault('id', f"{market}-d{c['day']}-c{c['slot']}")
    return build.rows_for(src, cases, market)


def outputs():
    files = {}
    groups, size = [[]], 0
    for m in markets():
        data = json.dumps(rows(m), ensure_ascii=False, indent=1)
        text = (f'// Generated by scripts/cases/export_loader.py from scripts/cases/{m}/. Do not edit by hand.\n'
                f'// Typed as unknown[] so a type check never infers this whole literal.\n'
                f'const rows: unknown[] = {data};\n\nexport default rows;\n')
        if groups[-1] and size + len(text.encode()) > BUNDLE_LIMIT:
            groups.append([]); size = 0
        groups[-1].append(m); size += len(text.encode())
        files[(len(groups) - 1, m)] = text
    out = {}
    for (g, m), text in files.items():
        out[os.path.join(function_dir(g), 'data', f'{m}.ts')] = text
    for g, names in enumerate(groups):
        fn = function_dir(g)
        imports = ''.join(f"import {m} from './{m}.ts';\n" for m in names)
        out[os.path.join(fn, 'data', 'index.ts')] = (
            '// Generated by scripts/cases/export_loader.py. Do not edit by hand.\n' + imports +
            '\n/** The hand-written Deep Cases bundled with this function, by market, as deep_cases rows. */\n'
            f"export const DEEP_CASES = {{ {', '.join(names)} }};\n")
        out[os.path.join(fn, 'index.ts')] = (
            '// Generated by scripts/cases/export_loader.py. Loads this function\'s share of the Deep Cases;\n'
            '// see supabase/functions/_shared/deep-cases-loader.ts.\n'
            'import { serveDeepCaseLoader } from "../_shared/deep-cases-loader.ts";\n'
            'import { DEEP_CASES } from "./data/index.ts";\n\nserveDeepCaseLoader(DEEP_CASES);\n')
    files = out
    files[SCHEMA_OUT] = (
        '-- The public.deep_cases table, for a Lovable migration (schema only; the cases are loaded by the\n'
        '-- load-deep-cases edge functions). Generated by scripts/cases/export_loader.py from build.SCHEMA.\n'
        + build.SCHEMA + "\nNOTIFY pgrst, 'reload schema';\n")
    return files


if __name__ == '__main__':
    check = '--check' in sys.argv
    stale = []
    outputs_cache = outputs()
    for path, text in outputs_cache.items():
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if current == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w', encoding='utf-8').write(text)
    owned = set(outputs_cache)
    for path in glob.glob(os.path.join(FUNCTIONS, 'load-deep-cases*', 'data', '*.ts')):
        if path not in owned:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.remove(path)
    if check and stale:
        print('out of date:', ', '.join(stale))
        sys.exit(1)
    print(('up to date' if check else f'wrote {len(stale)} file(s)') + f": {', '.join(markets())}")
