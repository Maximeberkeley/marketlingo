def call(situation, prompt, options, consequences, explanation, pro, mistake, model, sources=None):
    out = {
        'call': {'kind': 'theCall', 'situation': situation, 'prompt': prompt, 'options': options,
                 'correctIndex': 0, 'consequences': consequences, 'explanation': explanation},
        'pro': pro, 'mistake': mistake, 'model': model,
    }
    if sources:
        out['sources'] = sources
    return out


