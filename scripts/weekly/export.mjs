#!/usr/bin/env node
/**
 * node scripts/weekly/export.mjs [--write]
 * Validates every case, then emits the database upsert for them.
 *   (no flag)  prints the SQL
 *   --write    writes scripts/weekly/export/weekly_cases.generated.sql and .json (commit both with the case)
 * It refuses to export anything that fails validation.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { EXPORT_DIR, loadCases } from './lib/files.mjs';
import { validateSet } from './lib/validate.mjs';
import { toRows, toSQL } from './lib/mapping.mjs';

const write = process.argv.includes('--write');
const cases = loadCases();
if (cases.some(c => !c.data)) { console.error('A case file is not valid JSON.'); process.exit(1); }
const { results, setErrors } = validateSet(cases);
const failing = results.filter(r => r.errors.length);
if (failing.length || setErrors.length) {
  for (const r of failing) console.error(`✗ ${r.file}: ${r.errors.join(' | ')}`);
  for (const e of setErrors) console.error(`✗ ${e}`);
  console.error('Not exporting: fix the errors first (node scripts/weekly/validate.mjs).');
  process.exit(1);
}

const header = [
  '-- GENERATED by scripts/weekly/export.mjs from scripts/weekly/cases/*.json. Do not edit by hand.',
  '-- Idempotent: re-running updates the same weeks. Needs public.weekly_cases and public.weekly_case_scoring.',
  '',
].join('\n');
const sql = header + cases.map(c => toSQL(c.data)).join('\n');
const json = JSON.stringify(cases.map(c => toRows(c.data)), null, 2) + '\n';

if (write) {
  mkdirSync(EXPORT_DIR, { recursive: true });
  writeFileSync(join(EXPORT_DIR, 'weekly_cases.generated.sql'), sql);
  writeFileSync(join(EXPORT_DIR, 'weekly_cases.generated.json'), json);
  console.log(`Wrote ${cases.length} case(s) to scripts/weekly/export/.`);
} else process.stdout.write(sql);
