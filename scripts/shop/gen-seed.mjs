#!/usr/bin/env node
/**
 * Writes scripts/shop/catalog_seed.sql: an upsert of every shop item from mobile/lib/shopCatalog.ts, so the
 * server's shop_items match what the phone lists (same ids, prices, rules). The shop migration embeds this
 * file; after changing the catalog, run this and paste the output into a new migration.
 *
 *   node scripts/shop/gen-seed.mjs
 */
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const { transformSync } = await import('esbuild');
const load = async rel => {
  const code = transformSync(readFileSync(join(ROOT, rel), 'utf8'), { loader: 'ts', format: 'esm', target: 'es2020' }).code;
  const file = join(mkdtempSync(join(tmpdir(), 'shop-')), 'mod.mjs');
  // Both modules are plain data with no imports, so they load on their own.
  writeFileSync(file, code);
  return import(pathToFileURL(file).href);
};
const cat = await load('mobile/lib/shopCatalog.ts');
const { ART_READY_IDS } = await load('mobile/lib/shopArtIds.ts');
const art = new Set(ART_READY_IDS);

const q = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const j = v => `'${JSON.stringify(v ?? {}).replace(/'/g, "''")}'::jsonb`;
const rows = [];
for (const c of cat.COSMETICS) {
  rows.push([q(c.id), q('cosmetic'), q(c.slot), q(c.rarity), q(c.name), q(cat.priceOf(c)), q(c.acquisition), j(c.requires), j(c.collection ? { collection: c.collection } : {}), q('live'), art.has(c.id), !!c.hidden]);
}
for (const p of cat.POWER_UPS) {
  rows.push([q(p.id), q(p.id === cat.STREAK_FREEZE_ID ? 'freeze' : 'powerup'), 'NULL', 'NULL', q(p.name), q(p.price), q('purchase'), j({}), j({}), q(p.live ? 'live' : 'coming_soon'), true, false]);
}
for (const p of cat.PERKS) {
  rows.push([q(p.id), q('perk'), 'NULL', 'NULL', q(p.name), q(p.price), q('purchase'), j(p.requires), j({ kicker: p.kicker }), q('coming_soon'), true, false]);
}
for (const b of cat.BUNDLES) {
  rows.push([q(b.id), q('bundle'), 'NULL', 'NULL', q(b.name), q(b.price), q('purchase'), j({}), j({ items: b.items, collection: b.collection }), q('live'), b.items.every(id => art.has(id)), false]);
}
const sql = `-- GENERATED by scripts/shop/gen-seed.mjs from mobile/lib/shopCatalog.ts. Re-run after catalog changes.
INSERT INTO public.shop_items (id, kind, slot, rarity, name, price, acquisition, requirements, meta, status, art_ready, hidden) VALUES
${rows.map(r => `  (${r.join(', ')})`).join(',\n')}
ON CONFLICT (id) DO UPDATE SET
  kind = EXCLUDED.kind, slot = EXCLUDED.slot, rarity = EXCLUDED.rarity, name = EXCLUDED.name, price = EXCLUDED.price,
  acquisition = EXCLUDED.acquisition, requirements = EXCLUDED.requirements, meta = EXCLUDED.meta, status = EXCLUDED.status,
  art_ready = EXCLUDED.art_ready, hidden = EXCLUDED.hidden;
`;
writeFileSync(join(ROOT, 'scripts', 'shop', 'catalog_seed.sql'), sql);
console.log(`${rows.length} items`);
