#!/usr/bin/env node
/**
 * Regenerates the phone's shop art registry from the files in mobile/assets/shop/.
 *
 *   node scripts/shop/gen-art-registry.mjs
 *
 * Drop a finished PNG at mobile/assets/shop/<slot>/<item-id>.png (slot: hat, glasses, outfit, cape, held,
 * background, frame; 1024 canvas exported at 768 px, transparent) or an icon at mobile/assets/shop/icons/<id>.png
 * (256 px), or an illustrated scene backdrop at mobile/assets/shop/scenes/<id>.png (1600x900, no text; id is a
 * collection id, a perk id or "promo"; it replaces the coded backdrop behind Leo on that card), then run this.
 * It writes:
 *   mobile/lib/shopArt.ts     static requires (the installed app never downloads art)
 *   mobile/lib/shopArtIds.ts  the ids that have art, for logic and tests that cannot load images
 *   scripts/shop/art_ready.sql  one UPDATE so the server's daily deals only pick items with art
 * plus the .js twins of the two phone files. Items without art stay placeholders and cannot be bought.
 */
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SHOP = join(ROOT, 'mobile', 'assets', 'shop');
const SLOTS = ['hat', 'glasses', 'outfit', 'cape', 'held', 'background', 'frame'];

const pngs = dir => (existsSync(join(SHOP, dir)) ? readdirSync(join(SHOP, dir)) : [])
  .filter(f => f.endsWith('.png') && !f.includes('@'))
  .map(f => f.slice(0, -4))
  .sort();

const layers = SLOTS.flatMap(slot => pngs(slot).map(id => ({ slot, id })));
const icons = pngs('icons');
const scenes = pngs('scenes');
if (!existsSync(join(SHOP, 'base', 'leo-base.png'))) throw new Error('mobile/assets/shop/base/leo-base.png is missing');
const dupes = layers.map(l => l.id).filter((id, i, all) => all.indexOf(id) !== i);
if (dupes.length) throw new Error(`Item art in two slots: ${dupes.join(', ')}`);

const req = path => `require('../assets/shop/${path}')`;
const head = '// GENERATED by scripts/shop/gen-art-registry.mjs from mobile/assets/shop. Do not edit by hand.\n';
const ts = `${head}import type { ImageSourcePropType } from 'react-native';

/** The approved bare Leo bust every layer is stacked on. */
export const LEO_BASE: ImageSourcePropType = ${req('base/leo-base.png')};

/** Leo layers by item id (same 1024 canvas as the base). */
export const SHOP_ART: Record<string, ImageSourcePropType> = {
${layers.map(l => `  '${l.id}': ${req(`${l.slot}/${l.id}.png`)},`).join('\n')}
};

/** Glossy shop icons by id. */
export const SHOP_ICONS: Record<string, ImageSourcePropType> = {
${icons.map(id => `  '${id}': ${req(`icons/${id}.png`)},`).join('\n')}
};

/** Illustrated scene backdrops by collection / perk id ("promo" for the featured card); none means the coded scene. */
export const SHOP_SCENES: Record<string, ImageSourcePropType> = {${scenes.length ? `\n${scenes.map(id => `  '${id}': ${req(`scenes/${id}.png`)},`).join('\n')}\n` : ''}};
`;
const idsTs = `${head}/** Item ids whose Leo layer art exists. */
export const ART_READY_IDS: string[] = [${layers.map(l => `'${l.id}'`).join(', ')}];

/** Shop icon ids that exist. */
export const ICON_IDS: string[] = [${icons.map(id => `'${id}'`).join(', ')}];
`;
const sql = `-- GENERATED by scripts/shop/gen-art-registry.mjs. Run after adding art so daily deals can pick the new items.
UPDATE public.shop_items SET art_ready = (id = ANY (ARRAY[${layers.map(l => `'${l.id}'`).join(', ')}]::text[])) WHERE kind = 'cosmetic';
`;
// The phone ships each .ts with a .js twin made by the same esbuild transform the tests check.
const { transformSync } = await import('esbuild');
const twin = code => transformSync(code, { loader: 'ts', format: 'esm', target: 'es2020' }).code;
writeFileSync(join(ROOT, 'mobile', 'lib', 'shopArt.ts'), ts);
writeFileSync(join(ROOT, 'mobile', 'lib', 'shopArt.js'), twin(ts));
writeFileSync(join(ROOT, 'mobile', 'lib', 'shopArtIds.ts'), idsTs);
writeFileSync(join(ROOT, 'mobile', 'lib', 'shopArtIds.js'), twin(idsTs));
writeFileSync(join(ROOT, 'scripts', 'shop', 'art_ready.sql'), sql);
console.log(`${layers.length} layers, ${icons.length} icons, ${scenes.length} scenes`);
